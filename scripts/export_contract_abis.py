#!/usr/bin/env python3
"""Export the read/parameter-execution ABI directly from compiled Solidity artifacts."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = '// Generated by scripts/export_contract_abis.py after forge build.\n'
    for name in ['BlueRouter', 'BlueOracle', 'BlueRiskExecutor', 'BlueBorrowPermission']:
        source = ROOT / f'protocol-old/out/{name}.sol/{name}.json'
        abi = [item for item in json.loads(source.read_text())['abi'] if item['type'] in {'function','event','error'}]
        text += f'export const {name}Abi = ' + json.dumps(abi,indent=2) + ' as const;\n'
    for relative in ['frontend/src/lib/blue/abi.generated.ts', 'keepers/src/generated/blueAbi.ts']:
        target = ROOT / relative
        if args.check:
            if not target.exists() or target.read_text() != text:
                raise SystemExit('Regenerate ABI: python3 scripts/export_contract_abis.py')
        else:
            target.parent.mkdir(exist_ok=True)
            target.write_text(text)


if __name__ == '__main__':
    main()
