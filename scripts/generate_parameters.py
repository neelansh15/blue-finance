#!/usr/bin/env python3
"""Generate checked-in consumers of the declared, uncalibrated risk schema."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REGIMES = ['OPEN', 'EXTENDED', 'CLOSED', 'WEEKEND', 'HALTED', 'CORP_ACTION']


def outputs():
    source = ROOT / 'config/blue-risk.v1.json'
    data = json.loads(source.read_text())
    if data['schema_version'] != 1 or data['regime_order'] != REGIMES or data['status'] != 'UNCALIBRATED':
        raise ValueError('Unsupported risk schema, regime order or calibration claim')
    blue = data['blue']
    for key in ['haircuts_bps', 'staleness_seconds', 'regime_caps_usd']:
        if set(blue[key]) != set(REGIMES):
            raise ValueError(f'{key} must declare exactly six regimes')
    if any(not isinstance(h, int) or not 0 <= h <= 5000 for h in blue['haircuts_bps'].values()):
        raise ValueError('Haircut outside oracle bounds')
    if not 0 <= blue['margin_bps'] <= 5000:
        raise ValueError('Margin outside router bounds')
    if any(not isinstance(t, int) or not 0 < t < 2**32 for t in blue['staleness_seconds'].values()):
        raise ValueError('Invalid staleness')
    if any(not 0 <= cap <= blue['total_borrow_cap_usd'] for cap in blue['regime_caps_usd'].values()):
        raise ValueError('Invalid regime cap')
    if blue['regime_caps_usd']['HALTED'] or blue['regime_caps_usd']['CORP_ACTION']:
        raise ValueError('Special regimes must block new exposure')
    canonical = json.dumps(data, sort_keys=True, separators=(',', ':'), allow_nan=False)
    digest = hashlib.sha256(canonical.encode()).hexdigest()
    data['configuration_sha256'] = digest
    preamble = '// Generated by scripts/generate_parameters.py; edit config/blue-risk.v1.json.\n'
    ts = preamble + 'export const RISK_PARAMETERS = ' + json.dumps(data, indent=2) + ' as const;\n'
    constants = [('uint256', 'LLTV', data['market']['lltv_wad'])]
    constants += [('uint16', 'H_' + r, blue['haircuts_bps'][r]) for r in REGIMES]
    constants += [('uint256', 'TOTAL_CAP', int(blue['total_borrow_cap_usd']) * 10**blue['loan_decimals']),
                  ('uint256', 'SUPPLY_CAP', int(blue['supply_cap_tokens']) * 10**blue['collateral_decimals'])]
    names = {'margin_bps':'MARGIN_BPS', 'continuity_band_bps':'CONTINUITY_BAND_BPS',
             'jump_band_bps':'JUMP_BAND_BPS', 'max_freeze_seconds':'MAX_FREEZE',
             'expired_freeze_haircut_bps':'EXPIRED_FREEZE_HAIRCUT_BPS',
             'max_override_seconds':'MAX_OVERRIDE', 'eligibility_ttl_seconds':'MAX_ATTESTATION_TTL'}
    constants += [('uint256' if k == 'eligibility_ttl_seconds' else 'uint64' if k.endswith('_seconds') else 'uint32' if k == 'jump_band_bps' else 'uint16', v, blue[k]) for k,v in names.items()]
    constants += [('uint64', k.upper(), v) for k,v in data['monitoring'].items()]
    constants += [('uint64', k.upper(), v) for k,v in data['execution'].items()]
    sol = '// SPDX-License-Identifier: MIT\npragma solidity 0.8.28;\n\n' + preamble
    sol += 'library BlueRiskParameters {\n'
    sol += f'    bytes32 internal constant CONFIG_HASH = 0x{digest};\n'
    sol += ''.join(f'    {kind} internal constant {name} = {value};\n' for kind,name,value in constants)
    for name,kind,values in [('haircuts','uint16',[blue['haircuts_bps'][r] for r in REGIMES]),
                              ('mockStaleness','uint32',[blue['staleness_seconds'][r] for r in REGIMES]),
                              ('atlasStaleness','uint32',[data['atlas_staleness_seconds'][r] for r in REGIMES]),
                              ('regimeCaps','uint256',[int(blue['regime_caps_usd'][r])*10**blue['loan_decimals'] for r in REGIMES])]:
        sol += f'    function {name}() internal pure returns ({kind}[6] memory) {{\n'
        sol += f'        return [{kind}({values[0]}), ' + ', '.join(map(str,values[1:])) + '];\n    }\n'
    sol += '}\n'
    return {'frontend/src/lib/blue/generated.ts':ts, 'keepers/src/generated/riskParameters.ts':ts,
            'protocol-old/src/generated/BlueRiskParameters.sol':sol,
            'ai-risk-controller/app/generated/blue_parameters.json':json.dumps(data,indent=2)+'\n'}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for relative, content in outputs().items():
        target = ROOT / relative
        if args.check:
            if not target.exists() or target.read_text() != content:
                stale.append(relative)
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content)
    if stale:
        raise SystemExit('Regenerate risk parameters: ' + ', '.join(stale))


if __name__ == '__main__':
    main()
