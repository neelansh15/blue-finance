#!/usr/bin/env bash
# Starts (or restarts) an anvil BSC fork on :8545, deploys Blue, writes deployments/56.json,
# keepers/.env.anvil and frontend/.env.local. Idempotent: always kills the old anvil first.
set -euo pipefail
D="$(cd "$(dirname "$0")" && pwd)"; R="$(dirname "$D")"
source "$D/config.env"
mkdir -p "$D/logs"

if pgrep -f "anvil .*--port ${ANVIL_PORT}" >/dev/null; then
  pkill -f "anvil .*--port ${ANVIL_PORT}" || true
  for _ in $(seq 20); do pgrep -f "anvil .*--port ${ANVIL_PORT}" >/dev/null || break; sleep 0.5; done
fi
rm -f "$R/protocol/deployments/56.json"

nohup anvil --fork-url "$FORK_URL" --port "$ANVIL_PORT" --host 127.0.0.1 --chain-id "$CHAIN_ID" \
  --retries 10 --timeout 60000 > "$D/logs/anvil.log" 2>&1 &
echo $! > "$D/anvil.pid"
for i in $(seq 60); do
  if cast chain-id --rpc-url "$RPC_URL" >/dev/null 2>&1; then break; fi; sleep 1
  [ "$i" = 60 ] && { echo "anvil did not start, see $D/logs/anvil.log"; exit 1; }
done
echo "anvil up (pid $(cat "$D/anvil.pid")), chain $(cast chain-id --rpc-url "$RPC_URL")"
FORK_BLOCK=$(cast block-number --rpc-url "$RPC_URL")

cd "$R/protocol"
[ -d lib/forge-std ] || forge install foundry-rs/forge-std@v1.9.7 --no-git
PRIVATE_KEY=$DEPLOYER_KEY KEEPER=$(cast wallet address $KEEPER_KEY) SEED_SUPPLY=$SEED_SUPPLY \
  INITIAL_PRICE=$INITIAL_PRICE ANVIL_FUND_USDT=true \
  forge script script/Deploy.s.sol --rpc-url "$RPC_URL" --broadcast > "$D/logs/deploy.log" 2>&1 \
  || { tail -30 "$D/logs/deploy.log"; exit 1; }
cp deployments/56.json "$D/deployments-56.json" 2>/dev/null || true
J=deployments/56.json
j() { node -e "console.log(JSON.parse(require('fs').readFileSync('$J','utf8'))['$1'])"; }
TOKEN=$(j mockBStock); ORACLE=$(j blueOracle); REG=$(j regimeRegistry); ROUTER=$(j blueRouter)
FEED=$(j mockAtlasFeed); MORPHO=$(j morpho); MID=$(j marketId); USDT=$(j usdt)
SIGNER_KEY=$(cast keccak "blue.demo.eligibility.signer")
USER=$(cast wallet address $USER_KEY); LIQ=$(cast wallet address $LIQUIDATOR_KEY)

# fund demo user and liquidator (owner of mock = deployer)
cast send "$TOKEN" "mint(address,uint256)" "$USER" "$USER_COLLATERAL_WEI" --private-key $DEPLOYER_KEY --rpc-url "$RPC_URL" >/dev/null
fund_usdt() { # who amount
  local slot; slot=$(cast index address "$1" 1)  # BSC-USD balances mapping slot 1
  cast rpc anvil_setStorageAt "$USDT" "$slot" "$(cast to-uint256 "$2")" --rpc-url "$RPC_URL" >/dev/null
}
fund_usdt "$USER" "$USER_USDT_WEI"; fund_usdt "$LIQ" "$LIQ_USDT_WEI"
BAL=$(cast call "$USDT" "balanceOf(address)(uint256)" "$USER" --rpc-url "$RPC_URL" | awk '{print $1}')
[ "$BAL" = "$USER_USDT_WEI" ] || echo "WARNING: USDT balance slot guess failed for demo user (got $BAL)"
# liquidation callback contract, owned by the liquidator EOA, pre-funded with USDT (pre-funded repay mode)
IRM=$(j irm); LLTV=$(j lltv)
LIQC=$(forge create src/LiquidatorCallback.sol:LiquidatorCallback --rpc-url "$RPC_URL" --private-key $DEPLOYER_KEY --broadcast \
  --constructor-args "$MORPHO" "$LIQ" 2>>"$D/logs/deploy.log" | awk '/Deployed to:/{print $3}')
[ -n "$LIQC" ] || { echo "LiquidatorCallback deploy failed"; exit 1; }
fund_usdt "$LIQC" "$LIQ_USDT_WEI"
MARKET_PARAMS="{\"loanToken\":\"$USDT\",\"collateralToken\":\"$TOKEN\",\"oracle\":\"$ORACLE\",\"irm\":\"$IRM\",\"lltv\":\"$LLTV\"}"

cat > "$R/frontend/.env.local" <<ENV
# generated by demo/start.sh. Public demo-only values.
NEXT_PUBLIC_BLUE_MODE=real
NEXT_PUBLIC_BLUE_RPC_URL=$RPC_URL
NEXT_PUBLIC_BLUE_CHAIN_ID=$CHAIN_ID
NEXT_PUBLIC_BLUE_TOKEN=$TOKEN
NEXT_PUBLIC_BLUE_ORACLE=$ORACLE
NEXT_PUBLIC_BLUE_REGISTRY=$REG
NEXT_PUBLIC_BLUE_ROUTER=$ROUTER
NEXT_PUBLIC_BLUE_MORPHO=$MORPHO
NEXT_PUBLIC_BLUE_MARKET_ID=$MID
NEXT_PUBLIC_BLUE_FEED=$FEED
NEXT_PUBLIC_BLUE_ACCOUNT=$USER
# Demo-only user key (public anvil key) so the UI can sign without a wallet extension.
NEXT_PUBLIC_BLUE_DEMO_USER_KEY=$USER_KEY
# Demo-only eligibility signer key, public by design (keccak256("blue.demo.eligibility.signer")).
NEXT_PUBLIC_BLUE_DEMO_SIGNER_KEY=$SIGNER_KEY
ENV

ASSETS="[{\"symbol\":\"bAAPL\",\"ticker\":\"AAPL\",\"token\":\"$TOKEN\",\"feed\":\"$FEED\",\"oracle\":\"$ORACLE\"}]"
cat > "$R/keepers/.env.anvil" <<ENV
# generated by demo/start.sh. Anvil fork only. Keys are public anvil keys.
RPC_URL=$RPC_URL
CHAIN_ID=$CHAIN_ID
REGIME_REGISTRY=$REG
ASSETS='$ASSETS'
KEEPER_PRIVATE_KEY=$KEEPER_KEY
DRY_RUN=false
POLL_INTERVAL_MS=$POLL_INTERVAL_MS
OVERRIDE_DURATION_S=$OVERRIDE_DURATION_S
CONTINUITY_BAND_BPS=$CONTINUITY_BAND_BPS
MORPHO=$MORPHO
MARKET_ID=$MID
MARKET_PARAMS='$MARKET_PARAMS'
LIQUIDATOR=$LIQC
LIQUIDATOR_PRIVATE_KEY=$LIQUIDATOR_KEY
FROM_BLOCK=$((FORK_BLOCK+1))
LOG_CHUNK=2000
ENV
if [ -n "${WARP_TO:-}" ]; then
  cast rpc evm_setNextBlockTimestamp "$WARP_TO" --rpc-url "$RPC_URL" >/dev/null
  cast rpc evm_mine --rpc-url "$RPC_URL" >/dev/null
  cast send "$FEED" "setAnswer(int256)" "$INITIAL_PRICE" --private-key "$DEPLOYER_KEY" --rpc-url "$RPC_URL" >/dev/null 2>&1 || true  # refresh feed timestamp after the warp
  cast send "$ORACLE" "update()" --private-key "$DEPLOYER_KEY" --rpc-url "$RPC_URL" >/dev/null 2>&1 || true
  echo "chain time warped to $WARP_TO"
fi
echo "liquidator callback: $LIQC"
echo "deployed: registry=$REG oracle=$ORACLE router=$ROUTER token=$TOKEN market=$MID"
echo "wrote protocol/deployments/56.json frontend/.env.local keepers/.env.anvil"
